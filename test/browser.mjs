import { chromium } from 'playwright';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import assert from 'node:assert/strict';
import { app, run } from '../server.js';
const directory = await mkdtemp(join(tmpdir(),'loop-browser-'));
const server = app.listen(0,'127.0.0.1'); await new Promise(resolve=>server.once('listening',resolve));
const browser = await chromium.launch({executablePath:process.env.CHROMIUM_PATH || '/usr/bin/chromium',headless:true,args:['--no-sandbox']});
try {
  const page = await browser.newPage({viewport:{width:1440,height:1000}});
  const errors = []; page.on('pageerror',err=>errors.push(err.message));
  await page.goto(`http://127.0.0.1:${server.address().port}`);
  assert.equal(await page.locator('#export').isDisabled(),true);
  await page.screenshot({path:join(tmpdir(),'loop-studio-desktop.png'),fullPage:true});
  const fixture = join(directory,'sample.mp4');
  await run('ffmpeg',['-v','error','-f','lavfi','-i','testsrc2=size=640x360:rate=30','-f','lavfi','-i','sine=frequency=440:sample_rate=48000','-t','6','-c:v','libx264','-threads','2','-pix_fmt','yuv420p','-c:a','aac',fixture]);
  await page.locator('#file').setInputFiles(fixture);
  await page.waitForFunction(()=>!document.querySelector('#export').disabled);
  await page.locator('#mode').selectOption('normal');
  await page.locator('#start').fill('0.5'); await page.locator('#start').press('Tab');
  await page.locator('#end').fill('1.5'); await page.locator('#end').press('Tab');
  assert.equal(await page.locator('#total-duration').textContent(),'3 detik');
  await page.locator('#play').click();
  await page.waitForTimeout(2500);
  const state = await page.locator('#video').evaluate(v=>({paused:v.paused,time:v.currentTime}));
  assert.equal(state.paused,false); assert.ok(state.time>=0.5 && state.time<1.65,JSON.stringify(state));
  await page.locator('#play').click();
  await page.locator('#mute').check();
  await page.locator('#export').click();
  await page.locator('#download').waitFor({state:'visible',timeout:30000});
  const [download] = await Promise.all([page.waitForEvent('download'),page.locator('#download').click()]);
  const output = join(directory,'download.mp4'); await download.saveAs(output);
  const info = JSON.parse(await run('ffprobe',['-v','error','-show_format','-show_streams','-of','json',output]));
  assert.ok(Math.abs(Number(info.format.duration)-3)<0.2);
  assert.equal(info.streams.some(s=>s.codec_type==='audio'),false);
  await page.locator('#full-range').click();
  await page.locator('#mute').uncheck();
  await page.locator('#analyze').click();
  await page.waitForFunction(()=>document.querySelectorAll('.candidate').length>0 && !document.querySelector('#preview').disabled,{},{timeout:60000});
  assert.equal(await page.locator('#mode').inputValue(),'seamless');
  assert.ok((await page.locator('.candidate').count())>=2);
  await page.locator('.candidate').nth(1).click();
  assert.equal(await page.locator('.candidate').nth(1).getAttribute('aria-pressed'),'true');
  await page.locator('#preview').click();
  await page.locator('#seam-preview').waitFor({state:'visible',timeout:60000});
  await page.waitForFunction(()=>document.querySelector('#seam-preview').readyState>=2);
  assert.match(await page.locator('#preview-note').textContent(),/Sambungan berada/);
  await page.locator('#seam-preview').evaluate(v=>v.play());
  await page.waitForTimeout(500);
  assert.equal(await page.locator('#seam-preview').evaluate(v=>v.paused),false);
  await page.locator('#seam-preview').evaluate(v=>v.pause());
  await page.locator('#output-mode').selectOption('duration');
  await page.locator('#target-duration').fill('6.2'); await page.locator('#target-duration').press('Tab');
  assert.equal(await page.locator('#total-duration').textContent(),'6.2 detik');
  await page.locator('#export').click();
  await page.locator('#download').waitFor({state:'visible',timeout:60000});
  const [autoDownload] = await Promise.all([page.waitForEvent('download'),page.locator('#download').click()]);
  const autoOutput=join(directory,'auto.mp4');await autoDownload.saveAs(autoOutput);
  const autoInfo=JSON.parse(await run('ffprobe',['-v','error','-show_format','-show_streams','-of','json',autoOutput]));
  assert.ok(Math.abs(Number(autoInfo.format.duration)-6.2)<0.08);
  assert.equal(autoInfo.streams.some(s=>s.codec_type==='audio'),true);
  assert.equal(await page.locator('#validation').isVisible(),true);
  await page.evaluate(()=>window.scrollTo(0,0));
  await page.screenshot({path:join(tmpdir(),'loop-studio-loaded.png'),fullPage:true});
  await page.setViewportSize({width:390,height:844});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),true);
  await page.screenshot({path:join(tmpdir(),'loop-studio-mobile.png'),fullPage:true});
  await page.locator('#reset').click(); assert.equal(await page.locator('#export').isDisabled(),true);
  assert.equal(await page.locator('#empty-state').isVisible(),true);
  assert.deepEqual(errors,[]);
  console.log('PASS: upload, frame selection, playback, mute, automatic video/audio analysis, candidate selection, rendered preview, target-duration export, MP4 download, mobile layout, reset; no browser errors.');
} finally { await browser.close(); await new Promise(resolve=>server.close(resolve)); await rm(directory,{recursive:true,force:true}); }
